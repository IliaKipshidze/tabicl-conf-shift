"""Retain the ten winners selected only by matching-validation AUROC."""

from __future__ import annotations

import argparse
import csv
import io
import json
import os
import shutil
import tempfile
from pathlib import Path
from typing import Any

from .train import _sha256_file
from .tune import LEARNING_RATES, trial_spec, validate_trial_result

WINNERS_FORMAT = "nano_graph_u_lr_winners_v1"


def _check_existing(path: Path, contents: bytes) -> None:
    if path.exists() and path.read_bytes() != contents:
        raise FileExistsError(f"Refusing to replace a different selection: {path}")


def _atomic_write(path: Path, contents: bytes) -> None:
    if path.exists():
        _check_existing(path, contents)
        return
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(contents)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def _retain_checkpoint(source: Path, destination: Path, expected_hash: str) -> None:
    if destination.exists():
        if _sha256_file(destination) != expected_hash:
            raise FileExistsError(
                f"Refusing to replace a different winner: {destination}"
            )
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            dir=destination.parent, delete=False
        ) as stream:
            temporary = Path(stream.name)
        shutil.copyfile(source, temporary)
        if _sha256_file(temporary) != expected_hash:
            raise ValueError(f"Selected checkpoint changed while copying: {source}")
        os.replace(temporary, destination)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def select_winners(data_root: str | Path, output_root: str | Path) -> dict[str, Any]:
    """Validate all 100 trials, then retain one winner per repetition/condition.

    Exact AUROC ties are resolved by the smaller learning rate. Neither test
    banks nor test scores are read. Repeating an unchanged selection is safe;
    an existing, different selection is never overwritten.
    """
    data_root = Path(data_root).expanduser().resolve()
    output_root = Path(output_root).expanduser().resolve()
    specs = [trial_spec(task_id, data_root, output_root) for task_id in range(1, 101)]
    missing = [
        spec["result_path"] for spec in specs if not Path(spec["result_path"]).is_file()
    ]
    if missing:
        raise FileNotFoundError(
            f"Cannot select winners: {len(missing)} of 100 validation results are missing; "
            f"first missing result: {missing[0]}"
        )

    candidates = []
    validation_hashes: dict[str, str] = {}
    generator_fingerprint = None
    hash_cache: dict = {}
    for spec in specs:
        result = json.loads(Path(spec["result_path"]).read_text(encoding="utf-8"))
        score = validate_trial_result(
            result, spec, verify_files=True, hash_cache=hash_cache
        )
        report = result["validation_report"]
        condition = spec["condition"]
        if (
            validation_hashes.setdefault(condition, report["dump_sha256"])
            != report["dump_sha256"]
        ):
            raise ValueError(f"Validation bank differs between {condition} trials")
        fingerprint = report["dump_metadata"]["generator_source_sha256"]
        if generator_fingerprint is None:
            generator_fingerprint = fingerprint
        elif fingerprint != generator_fingerprint:
            raise ValueError("Candidates were generated by different prior code")
        candidates.append((spec, report, score))

    winner_dir = output_root / "winners"
    winners = []
    for repetition in range(1, 6):
        for condition in ("identity", "shift"):
            group = [
                candidate
                for candidate in candidates
                if candidate[0]["repetition"] == repetition
                and candidate[0]["condition"] == condition
            ]
            spec, report, score = max(
                group, key=lambda item: (item[2], -item[0]["learning_rate"])
            )
            destination = winner_dir / f"rep_{repetition}" / condition / "model.pt"
            winners.append(
                {
                    "repetition": repetition,
                    "condition": condition,
                    "task_id": spec["task_id"],
                    "learning_rate": spec["learning_rate"],
                    "model_seed": spec["model_seed"],
                    "validation_roc_auc": score,
                    "checkpoint_step": report["checkpoint_step"],
                    "checkpoint": str(destination),
                    "checkpoint_sha256": report["checkpoint_sha256"],
                    "source_checkpoint": report["checkpoint"],
                    "validation_dump": report["dump"],
                    "validation_dump_sha256": report["dump_sha256"],
                    "validation_result": spec["result_path"],
                }
            )

    manifest = {
        "format": WINNERS_FORMAT,
        "data_root": str(data_root),
        "output_root": str(output_root),
        "selection_metric": "roc_auc",
        "validation_policy": "matching_training_condition",
        "tie_break": "lowest_learning_rate",
        "training_steps": 2500,
        "trial_count": 100,
        "generator_source_sha256": generator_fingerprint,
        "learning_rates": list(LEARNING_RATES),
        "winners": winners,
    }
    manifest_bytes = (
        json.dumps(manifest, indent=2, sort_keys=True, allow_nan=False) + "\n"
    ).encode()
    summary = io.StringIO(newline="")
    columns = [
        "repetition",
        "condition",
        "learning_rate",
        "model_seed",
        "validation_roc_auc",
        "checkpoint_step",
        "task_id",
        "checkpoint",
        "checkpoint_sha256",
    ]
    writer = csv.DictWriter(summary, fieldnames=columns, extrasaction="ignore")
    writer.writeheader()
    writer.writerows(winners)
    summary_bytes = summary.getvalue().encode()
    manifest_path, summary_path = (
        winner_dir / "winners.json",
        winner_dir / "summary.csv",
    )
    _check_existing(manifest_path, manifest_bytes)
    _check_existing(summary_path, summary_bytes)
    # Check all retained files before writing any, including partial prior selections.
    for winner in winners:
        destination = Path(winner["checkpoint"])
        if (
            destination.exists()
            and _sha256_file(destination) != winner["checkpoint_sha256"]
        ):
            raise FileExistsError(
                f"Refusing to replace a different winner: {destination}"
            )
    for winner in winners:
        _retain_checkpoint(
            Path(winner["source_checkpoint"]),
            Path(winner["checkpoint"]),
            winner["checkpoint_sha256"],
        )
    _atomic_write(summary_path, summary_bytes)
    _atomic_write(manifest_path, manifest_bytes)
    return manifest


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", required=True)
    parser.add_argument("--output-root", required=True)
    args = parser.parse_args(argv)
    manifest = select_winners(args.data_root, args.output_root)
    for winner in manifest["winners"]:
        print(
            f"rep={winner['repetition']} condition={winner['condition']} "
            f"lr={winner['learning_rate']:g} validation_auc={winner['validation_roc_auc']:.6f} "
            f"checkpoint={winner['checkpoint']}",
            flush=True,
        )
    print(
        f"WINNERS_READY manifest={Path(args.output_root).expanduser().resolve() / 'winners' / 'winners.json'}"
    )


if __name__ == "__main__":
    main()
